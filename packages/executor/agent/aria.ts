export function buildShortRefMap({ refs }: { refs: Array<{ ref: string }> }): Map<string, string> {
  const map = new Map<string, string>();
  refs.forEach((entry, index) => {
    map.set(entry.ref, `e${index + 1}`);
  });
  return map;
}

