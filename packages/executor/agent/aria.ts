/**
 * Resolve a FrameLocator to an actual Frame object. FrameLocator (returned by
 * locator.contentFrame()) is a scoping helper that doesn't have CDP methods like
 * frameId(). We need the real Frame from page.frames() for OOPIF session attachment.
 *
 * If a Frame is passed directly, it's returned as-is.
 * If a FrameLocator is passed, we find the matching Frame by locating the iframe
 * element and matching its src URL against page.frames().
 */

function isTruthy<T>(value: T): value is NonNullable<T> {
  return Boolean(value);
}

/** A frame this module cannot snapshot through the page session; callers fall back. */
export class FrameOutOfReach extends Error {}

type FrameTree = { frame: { id: string; url: string; name?: string }; childFrames?: FrameTree[] };

// The CDP id of a Playwright frame, found by its URL and name in the page's frame tree. A frame
// that matches no or several entries has none here, as has a frame of another process.
async function frameIdOf(session: CDPSession, frame: Frame): Promise<string | null> {
  const { frameTree } = (await session.send("Page.getFrameTree")) as { frameTree: FrameTree };
  const all = (node: FrameTree): FrameTree["frame"][] => [
    node.frame,
    ...(node.childFrames ?? []).flatMap(all),
  ];
  const found = all(frameTree).filter(
    (candidate) => candidate.url === frame.url() && (candidate.name ?? "") === frame.name(),
  );
  return found.length === 1 ? (found[0]?.id ?? null) : null;
}

type LocatorParts = { _frame?: Frame; _selector?: string };

// The selector part before a ref's own locator: the frames to enter from the page's main frame,
// then the scope locator. With it, every ref of a frame or locator snapshot works as
// `page.locator()`.
async function refPrefix(
  page: Page,
  frame: Frame | undefined,
  locator: Locator | undefined,
): Promise<string> {
  const parts = locator as unknown as LocatorParts | undefined;
  const owner = parts?._frame ?? frame;
  const chain = owner && owner !== page.mainFrame() ? await frameScope(owner) : "";
  return typeof parts?._selector === "string" ? `${chain}${parts._selector} >> ` : chain;
}

/** The selector that enters a frame from its page's main frame, ending in ` >> `. */
export async function frameScope(frame: Frame): Promise<string> {
  const steps: string[] = [];
  for (
    let current = frame, parent = frame.parentFrame();
    parent;
    current = parent, parent = parent.parentFrame()
  ) {
    const owner = await current.frameElement();
    try {
      steps.unshift(await owner.evaluate(ownerSelector));
    } finally {
      await owner.dispose();
    }
  }
  return steps.map((step) => `${step} >> internal:control=enter-frame >> `).join("");
}

// A selector unique in its document for a frame's element: its id, its name, or its child path.
// It runs in the page.
function ownerSelector(element: Element): string {
  const document = element.ownerDocument;
  const unique = (selector: string) => document.querySelectorAll(selector).length === 1;
  const id = element.id ? `#${CSS.escape(element.id)}` : "";
  if (id && unique(id)) return id;
  const name = element.getAttribute("name");
  const named = name ? `${element.localName}[name="${CSS.escape(name)}"]` : "";
  if (named && unique(named)) return named;
  const path: string[] = [];
  for (
    let node: Element | null = element;
    node && node !== document.documentElement;
    node = node.parentElement
  ) {
    const siblings = node.parentElement ? [...node.parentElement.children] : [node];
    path.unshift(`${node.localName}:nth-child(${siblings.indexOf(node) + 1})`);
  }
  return `:root > ${path.join(" > ")}`;
}

export async function getAriaSnapshot({
  page,
  frame,
  locator,
  refFilter,
  interactiveOnly = false,
}: {
  page: Page;
  frame?: Frame | undefined;
  locator?: Locator | undefined;
  refFilter?: ((info: { role: string; name: string }) => boolean) | undefined;
  interactiveOnly?: boolean | undefined;
}): Promise<AriaSnapshotResult> {
  const session = await page.context().newCDPSession(page);
  // The scope mark is an attribute of this call alone, so neither the page's own attributes nor a
  // concurrent snapshot's mark is ever changed or removed.
  const scopeValue = crypto.randomUUID();
  const scopeAttr = `data-nds-scope-${scopeValue}`;
  const scopeLocator = locator;
  // The session is this call's own from here on: every exit below detaches it.
  try {
    const frameId = frame && frame !== page.mainFrame() ? await frameIdOf(session, frame) : null;
    if (frame && frame !== page.mainFrame() && !frameId) {
      throw new FrameOutOfReach(`frame ${frame.url()} is not reachable through its page`);
    }
    const resolvedFrame = frame;
    const prefix = await refPrefix(page, frame, locator);

    await Promise.all([
      session.send("DOM.enable"),
      session.send("Accessibility.enable"),
      // Blink updates its AX cache during rendering, after framework navigation changes the DOM.
      (resolvedFrame || page).evaluate(() => {
        return new Promise<void>((resolve) => {
          const window = document.defaultView;
          if (!window) {
            resolve();
            return;
          }
          if (document.visibilityState !== "visible") {
            document.documentElement.getBoundingClientRect();
            resolve();
            return;
          }
          window.requestAnimationFrame(() => {
            window.requestAnimationFrame(() => {
              resolve();
            });
          });
        });
      }),
    ]);

    if (scopeLocator) {
      await scopeLocator.evaluate(
        (element, data) => {
          element.setAttribute(data.attr, data.value);
        },
        { attr: scopeAttr, value: scopeValue },
      );
    }

    const { nodes: domNodes } = await session.send("DOM.getFlattenedDocument", {
      depth: -1,
      pierce: true,
    });
    const { domById, domByBackendId, childrenByParent } = buildDomIndex(domNodes);

    let scopeRootNodeId: NodeId | null = null;
    let scopeRootBackendId: BackendNodeId | null = null;
    if (scopeLocator) {
      scopeRootNodeId = findScopeRootNodeId(domNodes, scopeAttr, scopeValue);
      if (scopeRootNodeId) {
        const scopeNode = domById.get(scopeRootNodeId);
        if (scopeNode) {
          scopeRootBackendId = scopeNode.backendNodeId;
        }
      }
    }

    const allowedBackendIds = scopeRootNodeId
      ? buildBackendIdSet(scopeRootNodeId, childrenByParent, domById)
      : null;

    const axParams = frameId ? { frameId } : undefined;
    const { nodes: axNodes } = await session.send("Accessibility.getFullAXTree", axParams);

    const axById = new Map<AXNodeId, AXNode>();
    for (const node of axNodes) {
      axById.set(node.nodeId, node);
    }

    // Index AX nodes by backendDOMNodeId for O(1) lookups during promotion
    // and root finding (instead of repeated O(n) axNodes.find() calls)
    const axByBackendId = new Map<BackendNodeId, AXNode>();
    for (const node of axNodes) {
      if (node.backendDOMNodeId) {
        axByBackendId.set(node.backendDOMNodeId, node);
      }
    }

    // Promote contenteditable elements that Chrome's AX tree doesn't classify as
    // interactive. Rich text editors (ProseMirror, Tiptap, Slate, Lexical, etc.) use
    // bare <div contenteditable="true"> without role="textbox", so Chrome reports
    // them as "generic" and they become invisible in the snapshot. We detect these
    // via the DOM tree and override the AX role to "textbox" so they appear as
    // interactive elements the AI can target.
    const promotedContentEditableIds = new Set<BackendNodeId>();
    for (const [, domInfo] of domByBackendId) {
      if (!isContentEditable(domInfo.attributes.get("contenteditable"))) {
        continue;
      }
      const axNode = axByBackendId.get(domInfo.backendNodeId);
      if (!axNode) {
        continue;
      }
      const currentRole = getAxRole(axNode);
      if (INTERACTIVE_ROLES.has(currentRole)) {
        continue;
      }
      axNode.role = { type: "role", value: "textbox" };
      promotedContentEditableIds.add(domInfo.backendNodeId);
    }

    const findRootAxNodeId = (): AXNodeId | null => {
      if (scopeRootBackendId) {
        const scoped = axByBackendId.get(scopeRootBackendId);
        if (scoped) {
          return scoped.nodeId;
        }
      }
      const rootWebArea = axNodes.find((node) => {
        return getAxRole(node) === "rootwebarea";
      });
      if (rootWebArea) {
        return rootWebArea.nodeId;
      }
      const webArea = axNodes.find((node) => {
        return getAxRole(node) === "webarea";
      });
      if (webArea) {
        return webArea.nodeId;
      }
      const topLevel = axNodes.find((node) => {
        return !node.parentId;
      });
      return topLevel ? topLevel.nodeId : null;
    };

    const rootAxNodeId = findRootAxNodeId();

    const refCounts = new Map<string, number>();
    let fallbackCounter = 0;
    const refs: AriaRefDraft[] = [];

    const createRefForNode = (options: {
      backendNodeId?: BackendNodeId | undefined;
      role: string;
      name: string;
    }): string | null => {
      if (!INTERACTIVE_ROLES.has(options.role)) {
        return null;
      }

      const domInfo = options.backendNodeId ? domByBackendId.get(options.backendNodeId) : undefined;
      const stable = domInfo ? getStableRefFromAttributes(domInfo.attributes) : null;
      let baseRef = stable?.value;
      if (!baseRef) {
        fallbackCounter += 1;
        baseRef = `e${fallbackCounter}`;
      }

      const count = refCounts.get(baseRef) ?? 0;
      refCounts.set(baseRef, count + 1);
      const ref = count === 0 ? baseRef : `${baseRef}-${count + 1}`;

      let selector: string | undefined;
      if (stable && count === 0) {
        selector = buildLocatorFromStable(stable);
      }
      // For promoted contenteditable elements without a stable selector, store
      // [contenteditable="true"] so getSelectorForRef() doesn't fall back to
      // role=textbox which Playwright can't match on bare contenteditable divs.
      if (
        !selector &&
        options.backendNodeId != null &&
        promotedContentEditableIds.has(options.backendNodeId)
      ) {
        selector = '[contenteditable="true"]';
      }

      refs.push({
        ref,
        role: options.role,
        name: options.name,
        selector,
        backendNodeId: options.backendNodeId,
      });
      return ref;
    };

    const isNodeInScope = (node: AXNode): boolean => {
      if (!allowedBackendIds) {
        return true;
      }
      if (!node.backendDOMNodeId) {
        return false;
      }
      return allowedBackendIds.has(node.backendDOMNodeId);
    };

    let snapshotNodes: SnapshotNode[] = [];
    if (rootAxNodeId) {
      const rootNode = axById.get(rootAxNodeId);
      const rootRole = rootNode ? getAxRole(rootNode) : "";
      const rawRoots =
        rootNode && (rootRole === "rootwebarea" || rootRole === "webarea") && rootNode.childIds
          ? rootNode.childIds
              .map((childId) => {
                return buildRawSnapshotTree({ nodeId: childId, axById, isNodeInScope });
              })
              .filter(isTruthy)
          : [buildRawSnapshotTree({ nodeId: rootAxNodeId, axById, isNodeInScope })].filter(
              isTruthy,
            );

      const filtered = rawRoots.flatMap((rawNode) => {
        if (interactiveOnly) {
          return filterInteractiveSnapshotTree({
            node: rawNode,
            ancestorNames: [],
            labelContext: false,
            refFilter,
            domByBackendId,
            promotedContentEditableIds,
            createRefForNode,
          }).nodes;
        }
        return filterFullSnapshotTree({
          node: rawNode,
          ancestorNames: [],
          refFilter,
          domByBackendId,
          promotedContentEditableIds,
          createRefForNode,
        }).nodes;
      });
      snapshotNodes = filtered;
    }

    const snapshotLines = buildSnapshotLines(snapshotNodes);

    const shortRefMap = buildShortRefMap({ refs });
    const finalized = finalizeSnapshotOutput(snapshotLines, snapshotNodes, shortRefMap);
    const refsWithShortRef: Array<AriaRef & { selector?: string | undefined }> = refs.map(
      (entry) => {
        return {
          ...entry,
          shortRef: shortRefMap.get(entry.ref) ?? entry.ref,
        };
      },
    );
    const result = { snapshot: finalized.snapshot, tree: finalized.tree, refs: refsWithShortRef };

    // Build refToElement map
    const refToElement = new Map<string, { role: string; name: string; shortRef: string }>();
    const refToSelector = new Map<string, string>();
    for (const { ref, role, name, shortRef } of result.refs) {
      if (!refFilter || refFilter({ role, name })) {
        refToElement.set(ref, { role, name, shortRef });
      }
    }

    for (const { ref, selector } of result.refs) {
      if (!selector) {
        continue;
      }
      refToSelector.set(ref, selector);
    }

    const snapshot = result.snapshot;

    // The locator each ref's line shows, with its nth among equal locators.
    const shown = new Map<string, string>();
    const collect = (nodes: AriaSnapshotNode[]): void => {
      for (const node of nodes) {
        if (node.ref && node.locator) shown.set(node.ref, node.locator);
        collect(node.children);
      }
    };
    collect(result.tree);

    // Every selector is the shown one after the frame and scope prefix, so it works as
    // `page.locator()` and names the element the line shows.
    const getSelectorForRef = (ref: string): string | null => {
      const mapped = shown.get(ref) ?? refToSelector.get(ref);
      if (mapped) {
        return prefix + mapped;
      }
      const info = refToElement.get(ref);
      if (!info) {
        return null;
      }
      const escapedName = info.name.replace(/"/g, '\\"');
      return `${prefix}role=${info.role}[name="${escapedName}"i]`;
    };

    return { snapshot, tree: result.tree, refs: result.refs, getSelectorForRef };
  } finally {
    if (scopeLocator) {
      await scopeLocator
        .evaluate(
          (element, data) => {
            if (element.getAttribute(data.attr) === data.value) element.removeAttribute(data.attr);
          },
          { attr: scopeAttr, value: scopeValue },
        )
        .catch(() => undefined);
    }
    await session.detach().catch(() => undefined);
  }
}
